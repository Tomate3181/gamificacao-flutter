-- EcoPlanet: tabelas base (GDD, seção 15).
--
-- Convenção: valores de enumeração em inglês (usados no código), textos
-- exibidos ao jogador em português.

-- ---------------------------------------------------------------------------
-- Perfil do jogador
-- ---------------------------------------------------------------------------
create table public.profiles (
  id            uuid primary key references auth.users (id) on delete cascade,
  nickname      text not null
                check (char_length(btrim(nickname)) between 3 and 20),
  energy        numeric(14, 2) not null default 0 check (energy >= 0),
  oxygen        numeric(16, 2) not null default 0 check (oxygen >= 0),
  total_points  integer not null default 0 check (total_points >= 0),
  last_seen     timestamptz not null default now(),
  created_at    timestamptz not null default now()
);

comment on table public.profiles is
  'Um perfil por usuário. energy, oxygen e total_points só mudam via RPC.';

create index profiles_total_points_idx on public.profiles (total_points desc);

-- ---------------------------------------------------------------------------
-- Catálogos (somente leitura para o cliente)
-- ---------------------------------------------------------------------------
create table public.planets (
  id           bigint generated by default as identity primary key,
  order_index  integer not null unique check (order_index >= 1),
  name         text not null,
  theme        text not null
               check (theme in ('desert', 'forest', 'island', 'tundra', 'mountain')),
  total_slots  integer not null check (total_slots > 0),
  base_cost    numeric(10, 2) not null check (base_cost > 0)
);

create table public.tree_species (
  id              bigint generated by default as identity primary key,
  name            text not null unique,
  cost            integer not null check (cost > 0),
  oxygen_per_sec  numeric(10, 2) not null check (oxygen_per_sec > 0),
  grow_seconds    integer not null check (grow_seconds > 0),
  rarity          text not null
                  check (rarity in ('common', 'uncommon', 'rare', 'epic', 'legendary')),
  -- Tema de planeta em que a espécie rende mais (null = sem bônus).
  bonus_theme     text
                  check (bonus_theme in ('desert', 'forest', 'island', 'tundra', 'mountain'))
);

create table public.upgrades (
  id               bigint generated by default as identity primary key,
  category         text not null
                   check (category in ('growth', 'production', 'cost', 'automation', 'energy')),
  name             text not null unique,
  description      text not null,
  max_level        integer not null default 10 check (max_level >= 1),
  base_cost        numeric(12, 2) not null default 50 check (base_cost > 0),
  cost_multiplier  numeric(6, 3) not null default 1.5 check (cost_multiplier >= 1),
  -- Efeito por nível. Ex.: 0.05 = 5% por nível.
  effect           numeric(8, 4) not null check (effect > 0)
);

create table public.missions (
  id           bigint generated by default as identity primary key,
  title        text not null unique,
  description  text not null,
  guidance     text not null,
  category     text not null
               check (category in ('energy_saving', 'recycling', 'reuse', 'mobility', 'conscious_consumption')),
  difficulty   text not null check (difficulty in ('easy', 'medium', 'hard')),
  points       integer not null check (points > 0)
);

create table public.achievements (
  id                  bigint generated by default as identity primary key,
  code                text not null unique,
  name                text not null,
  description         text not null,
  icon                text not null,
  condition_type      text not null
                      check (condition_type in (
                        'missions_completed', 'mission_days', 'category_missions',
                        'planets_completed', 'trees_planted'
                      )),
  condition_value     integer not null check (condition_value > 0),
  -- Usado só quando condition_type = 'category_missions'.
  condition_category  text,
  check ((condition_type = 'category_missions') = (condition_category is not null))
);

-- ---------------------------------------------------------------------------
-- Progresso do jogador (cada linha pertence a um usuário)
-- ---------------------------------------------------------------------------
create table public.user_planets (
  id                uuid primary key default gen_random_uuid(),
  user_id           uuid not null references public.profiles (id) on delete cascade,
  planet_id         bigint not null references public.planets (id),
  reforested_slots  integer not null default 0 check (reforested_slots >= 0),
  started_at        timestamptz not null default now(),
  completed_at      timestamptz,
  unique (user_id, planet_id)
);

create table public.user_trees (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references public.profiles (id) on delete cascade,
  user_planet_id  uuid not null references public.user_planets (id) on delete cascade,
  species_id      bigint not null references public.tree_species (id),
  slot_index      integer not null check (slot_index >= 0),
  planted_at      timestamptz not null default now(),
  -- Uma árvore por região do planeta.
  unique (user_planet_id, slot_index)
);

create index user_trees_user_id_idx on public.user_trees (user_id);
create index user_trees_species_id_idx on public.user_trees (species_id);

create table public.user_upgrades (
  user_id     uuid not null references public.profiles (id) on delete cascade,
  upgrade_id  bigint not null references public.upgrades (id),
  level       integer not null check (level >= 1),
  updated_at  timestamptz not null default now(),
  primary key (user_id, upgrade_id)
);

-- Ausência de linha = missão disponível.
create table public.user_missions (
  user_id       uuid not null references public.profiles (id) on delete cascade,
  mission_id    bigint not null references public.missions (id),
  status        text not null default 'in_progress'
                check (status in ('available', 'in_progress', 'completed')),
  started_at    timestamptz not null default now(),
  completed_at  timestamptz,
  -- A chave (user_id, mission_id) impede pontos repetidos pela mesma missão.
  primary key (user_id, mission_id),
  check ((status = 'completed') = (completed_at is not null))
);

create index user_missions_mission_id_idx on public.user_missions (mission_id);

create table public.user_achievements (
  user_id         uuid not null references public.profiles (id) on delete cascade,
  achievement_id  bigint not null references public.achievements (id),
  unlocked_at     timestamptz not null default now(),
  primary key (user_id, achievement_id)
);

create index user_achievements_achievement_id_idx
  on public.user_achievements (achievement_id);
create index user_planets_planet_id_idx on public.user_planets (planet_id);
create index user_upgrades_upgrade_id_idx on public.user_upgrades (upgrade_id);
